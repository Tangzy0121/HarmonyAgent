function anchor(pageRange: string, excerpt: string): SourceAnchor {
  return {
    sourceId: source.id,
    fileName: source.fileName,
    pageRange,
    excerpt,
  }
}

function compactChapterBlocks(
  chapterId: string,
  conceptId: string,
  pageRange: string,
  explanation: string,
  citation: string,
  question: string,
  correctText: string,
): BookBlock[] {
  const sourceAnchor = anchor(pageRange, citation)
  return [
    {
      id: `blk-explanation-${chapterId}`,
      type: 'explanation',
      status: 'ready',
      title: '建立判断框架',
      revision: 1,
      sourceAnchors: [sourceAnchor],
      body: explanation,
      keyPoint: '先说清输入、目标和反馈，再判断模型究竟学到了什么。',
    },
    {
      id: `blk-citation-${chapterId}`,
      type: 'citation',
      status: 'ready',
      title: '原文依据',
      revision: 1,
      sourceAnchors: [sourceAnchor],
      excerpt: citation,
      location: `第 ${pageRange} 页 · ${conceptId}`,
    },
    {
      id: `blk-quiz-${chapterId}`,
      type: 'quiz',
      status: 'ready',
      title: '快速验证',
      revision: 1,
      sourceAnchors: [sourceAnchor],
      conceptId,
      question,
      options: [
        { id: `${chapterId}-answer-a`, marker: 'A', text: '只看训练数据量。' },
        { id: `${chapterId}-answer-b`, marker: 'B', text: correctText },
        { id: `${chapterId}-answer-c`, marker: 'C', text: '只看模型名称。' },
      ],
      correctAnswerId: `${chapterId}-answer-b`,
      feedback: '判断应回到训练信号、任务目标和独立评估依据。',
    },
  ]
}

